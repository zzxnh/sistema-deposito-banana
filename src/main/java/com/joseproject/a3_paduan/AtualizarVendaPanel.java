    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        if (!validadarCampos()) {
            JOptionPane.showMessageDialog(this, "Preencha os campos obrigatórios!");
            return;
        }

        try {
            Venda venda = new Venda();

            venda.setIdVenda(
                    Integer.parseInt(txtIdVenda.getText()));

            venda.setQtdeCaixas(
                    Integer.parseInt(txtQtdeCaixas.getText()));

            venda.setPrecoUni(
                    Double.parseDouble(txtPrecoUni.getText()));

            venda.setValorTotal(
                    venda.getQtdeCaixas()
                    * venda.getPrecoUni());

            VendaDAO dao = new VendaDAO();

            dao.atualizar(venda);

            listarVendasPanel.listarVendas();

            limparCampos();

            JOptionPane.showMessageDialog(this, "Venda atualizada com sucesso! ");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnAtualizarActionPerformed


