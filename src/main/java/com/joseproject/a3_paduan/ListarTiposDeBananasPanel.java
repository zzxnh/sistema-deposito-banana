    public void listarTiposDeBananas() {
        DefaultTableModel model = (DefaultTableModel) tabelaTipos.getModel();
        model.setRowCount(0);

        TipoDeBananaDAO dao = new TipoDeBananaDAO();
        List<TipoDeBanana> lista = dao.listar();

        for (TipoDeBanana a : lista) {
            model.addRow(new Object[]{
                a.getIdTipoBanana(),
                a.getNomeTipoBanana(),
            });
        }
    }
