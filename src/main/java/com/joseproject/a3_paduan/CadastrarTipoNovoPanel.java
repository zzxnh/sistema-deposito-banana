    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if (!validarCampos()) {
            JOptionPane.showMessageDialog(this, "Preencha os campos obrigatórios!");
            return;
        }

        try {

            TipoDeBanana tipo = new TipoDeBanana();
            tipo.setNomeTipoBanana(txtTipo.getText());

            TipoDeBananaDAO dao = new TipoDeBananaDAO();

            dao.salvar(tipo);
            
            limparCampos();

            JOptionPane.showMessageDialog(this, "Tipo cadastrado com sucesso!");
        } catch (Exception  e) {
            JOptionPane.showMessageDialog(this, "Erro ao cadastar o tipo:\n" + e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

