    private void btnExcluirVendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirVendaActionPerformed
        if (!validadarCampos()) {
            JOptionPane.showMessageDialog(this, "Preencha os campos obrigatórios!");
            return;
        }

        try {
            int id = Integer.parseInt(txtIdVenda.getText());

            VendaDAO dao = new VendaDAO();

            dao.excluir(id);

            listarVendasPanel.listarVendas();

            limparCampos();

            JOptionPane.showMessageDialog(this, "Venda excluída com sucesso! ");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnExcluirVendaActionPerformed


