    private void calcularTotal() {
        String qtdValidar = txtQtdeCaixas.getText().trim();
        String precoValidar = txtPrecoUni.getText().trim();

        if (qtdValidar.isEmpty() || precoValidar.isEmpty()) {
            txtTotal.setText("");
            return;
        }

        try {

            int quantidade = Integer.parseInt(txtQtdeCaixas.getText());
            double preco = Double.parseDouble(txtPrecoUni.getText());

            double total = quantidade * preco;

            txtTotal.setText(String.valueOf(total));

        } catch (Exception e) {

            txtTotal.setText("");
        }
    }

    public void carregarClientes() {

        cmbNomeCliente.removeAllItems();

        ClienteDAO dao = new ClienteDAO();

        for (Cliente cliente : dao.listar()) {
            cmbNomeCliente.addItem(cliente.getNomeCliente());
        }
    }

    public void carregarTiposBanana() {

        cmbIdTipoBanana.removeAllItems();

        TipoDeBananaDAO dao = new TipoDeBananaDAO();

        for (TipoDeBanana tipo : dao.listar()) {
            cmbIdTipoBanana.addItem(tipo.getNomeTipoBanana());
        }
    }

    private void limparCampos() {
        cmbNomeCliente.setSelectedIndex(0);
        cmbIdTipoBanana.setSelectedIndex(0);
        txtPrecoUni.setText("");
        txtQtdeCaixas.setText("");
        txtTotal.setText("");
    }

    private boolean validarCampos() {
        int qtde = Integer.parseInt(txtQtdeCaixas.getText());
        double preco = Double.parseDouble(txtPrecoUni.getText());
        
        if (qtde <= 0 || preco <=0) {
            return false;
        }
      
        if (txtQtdeCaixas.getText().trim().isEmpty() || txtPrecoUni.getText().trim().isEmpty()) {
            return false;
        }
        return true;
    }

