    private void btnSalvarVendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarVendaActionPerformed
        if (!validarCampos()) {
            JOptionPane.showMessageDialog(this, "Preencha os campos obrigatórios!");
            return;
        }

        try {

            ClienteDAO clienteDAO
                    = new ClienteDAO();

            TipoDeBananaDAO tipoDAO
                    = new TipoDeBananaDAO();

            String nomeCliente
                    = cmbNomeCliente.getSelectedItem().toString();

            String nomeTipo
                    = cmbIdTipoBanana.getSelectedItem().toString();

            Cliente cliente
                    = clienteDAO.buscarPorNome(nomeCliente);

            TipoDeBanana tipo
                    = tipoDAO.buscarPorNome(nomeTipo);

            Venda venda = new Venda();

            venda.setCliente(cliente);
            venda.setTipoDeBanana(tipo);

            venda.setQtdeCaixas(
                    Integer.parseInt(
                            txtQtdeCaixas.getText()));

            venda.setPrecoUni(
                    Double.parseDouble(
                            txtPrecoUni.getText()));

            venda.setValorTotal(
                    venda.getQtdeCaixas()
                    * venda.getPrecoUni());

            VendaDAO vendaDAO
                    = new VendaDAO();

            vendaDAO.salvar(venda);

            limparCampos();

            JOptionPane.showMessageDialog(
                    this,
                    "Venda cadastrada com sucesso!");

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarVendaActionPerformed

