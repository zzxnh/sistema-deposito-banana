    public void listarVendas() {
        DefaultTableModel model = (DefaultTableModel) tabelaVendas.getModel();
        model.setRowCount(0);

        VendaDAO dao = new VendaDAO();
        List<Venda> lista = dao.listar();

        for (Venda a : lista) {
            model.addRow(new Object[]{
                a.getIdVenda(),
                a.getCliente().getIdCliente(),
                a.getCliente().getNomeCliente(),
                a.getTipoDeBanana().getNomeTipoBanana(),
                a.getQtdeCaixas(),
                a.getPrecoUni(),
                a.getValorTotal()
            });
        }
    }
