    private void btnApagarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApagarActionPerformed
        int linha = tabelaClientes.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um cliente!");
            return;
        }

        int idCliente = Integer.parseInt(
                tabelaClientes.getValueAt(linha, 0).toString());

        excluirClientePanel.carregarCliente(idCliente);

        cardLayout.show(mainPanel, "EXCLUIR CLIENTE");
    }//GEN-LAST:event_btnApagarActionPerformed

    private void tabelaClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaClientesMouseClicked
        int linha = tabelaClientes.getSelectedRow();

        txtNome.setText(tabelaClientes.getValueAt(linha, 1).toString());
        txtIdCliente.setText(tabelaClientes.getValueAt(linha, 0).toString());
    }//GEN-LAST:event_tabelaClientesMouseClicked

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        int linha = tabelaClientes.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um cliente!");
        }

        int idCliente = Integer.parseInt(
                tabelaClientes.getValueAt(linha, 0).toString());

        atualizarClientePanel.carregarCliente(idCliente);

        cardLayout.show(mainPanel, "ATUALIZAR CLIENTE");
    }//GEN-LAST:event_btnAtualizarActionPerformed


