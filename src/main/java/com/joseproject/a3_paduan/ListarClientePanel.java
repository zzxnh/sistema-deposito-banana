    public void listarClientes() {
        DefaultTableModel model = (DefaultTableModel) tabelaClientes.getModel();
        model.setRowCount(0);

        ClienteDAO dao = new ClienteDAO();
        List<Cliente> lista = dao.listar();

        for (Cliente a : lista) {
            model.addRow(new Object[]{
                a.getIdCliente(),
                a.getNomeCliente(),});
        }
    }
